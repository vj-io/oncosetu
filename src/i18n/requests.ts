export function tr(lang: Lang, key: RequestKey, vars?: Record<string, string | number>): string {
  const s = (lang === 'hi' ? hi : en)[key]
  return vars ? s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? '')) : s
}
